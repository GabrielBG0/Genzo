//! Generates the TypeScript side of the contract.
//!
//! The output is written to `contract/genzo.ts` by `genzo-cli contract write`
//! and checked in. Never edit that file by hand.

use ts_rs::{Config, TS};

use crate::api::{
    AdapterInfo, AdapterKind, Command, EngineInfo, Event, Handshake, HandshakeResult, Query,
    QueryResult,
};
use crate::contract::{CONTRACT_VERSION, ContractVersion};
use crate::frame::{PixelFormat, Rect, TILE_HEADER_LEN, TILE_MAGIC, TILE_SIZE, TileHeader};

fn decl<T: TS>(cfg: &Config) -> String {
    format!("export {}", T::decl(cfg))
}

/// The full text of `contract/genzo.ts`.
pub fn generate() -> String {
    // serde writes u64 as a JSON number, so the TypeScript type is `number`.
    let cfg = Config::new().with_large_int("number");
    let magic = String::from_utf8_lossy(&TILE_MAGIC);
    let decls = [
        decl::<ContractVersion>(&cfg),
        decl::<AdapterKind>(&cfg),
        decl::<AdapterInfo>(&cfg),
        decl::<Handshake>(&cfg),
        decl::<HandshakeResult>(&cfg),
        decl::<EngineInfo>(&cfg),
        decl::<PixelFormat>(&cfg),
        decl::<Rect>(&cfg),
        decl::<TileHeader>(&cfg),
        decl::<Command>(&cfg),
        decl::<Query>(&cfg),
        decl::<QueryResult>(&cfg),
        decl::<Event>(&cfg),
    ];

    let mut out = String::new();
    out.push_str("// Generated by `genzo-cli contract write` from backend/crates/model.\n");
    out.push_str("// Do not edit by hand. Change the Rust types and bump CONTRACT_VERSION.\n\n");
    out.push_str(&format!(
        "export const CONTRACT_VERSION = \"{CONTRACT_VERSION}\";\n\n"
    ));
    out.push_str(
        "/** Binary tile protocol constants. Layout: backend/crates/model/src/frame.rs. */\n",
    );
    out.push_str(&format!("export const TILE_MAGIC = \"{magic}\";\n"));
    out.push_str(&format!(
        "export const TILE_HEADER_LEN = {TILE_HEADER_LEN};\n"
    ));
    out.push_str(&format!("export const TILE_SIZE = {TILE_SIZE};\n"));
    out.push_str("export const PIXEL_FORMAT_CODES: Record<PixelFormat, number> = {\n");
    for f in [PixelFormat::Rgba8Srgb, PixelFormat::Rgba8DisplayP3] {
        let name = serde_json::to_string(&f).expect("serializable");
        out.push_str(&format!("  {name}: {},\n", f.code()));
    }
    out.push_str("};\n");
    for d in decls {
        out.push('\n');
        out.push_str(d.trim_end());
        out.push('\n');
    }
    out
}

/// FNV-1a 64-bit hash, used to detect contract changes in `contract/contract.lock`.
pub fn fingerprint(text: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in text.as_bytes() {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    format!("{h:016x}")
}

/// Contents of `contract/contract.lock`: the version and the fingerprint of
/// the generated TypeScript at that version.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct ContractLock {
    pub version: String,
    pub fingerprint: String,
}

impl ContractLock {
    /// The lock for the contract this build generates.
    pub fn current() -> Self {
        Self {
            version: CONTRACT_VERSION.to_owned(),
            fingerprint: fingerprint(&generate()),
        }
    }

    pub fn to_text(&self) -> String {
        let mut s = serde_json::to_string_pretty(self).expect("serializable");
        s.push('\n');
        s
    }

    pub fn from_text(text: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(text)
    }
}

/// Why the checked-in contract does not match this build.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ContractDrift {
    /// The types changed but `CONTRACT_VERSION` did not.
    VersionNotBumped { version: String },
    /// `CONTRACT_VERSION` went down or was otherwise not increased.
    VersionNotIncreased { from: String, to: String },
    /// The checked-in TypeScript or lock is stale. Regenerate it.
    Stale,
}

impl std::fmt::Display for ContractDrift {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::VersionNotBumped { version } => write!(
                f,
                "the contract types changed but CONTRACT_VERSION is still {version}; \
                 bump it in backend/crates/model/src/contract.rs"
            ),
            Self::VersionNotIncreased { from, to } => write!(
                f,
                "CONTRACT_VERSION must increase, but it went from {from} to {to}"
            ),
            Self::Stale => write!(
                f,
                "contract/ is out of date; run `cargo run -p genzo-cli -- contract write` in backend/"
            ),
        }
    }
}

/// Decides whether the contract on disk can be replaced by this build's.
///
/// `previous` is the checked-in lock. Returns `Ok` when nothing changed or
/// when the change comes with a version bump.
pub fn check_bump(previous: &ContractLock) -> Result<(), ContractDrift> {
    let now = ContractLock::current();
    if previous.fingerprint == now.fingerprint {
        return Ok(());
    }
    if previous.version == now.version {
        return Err(ContractDrift::VersionNotBumped {
            version: now.version,
        });
    }
    match (
        ContractVersion::parse(&previous.version),
        ContractVersion::parse(&now.version),
    ) {
        (Some(a), Some(b)) if b > a => Ok(()),
        _ => Err(ContractDrift::VersionNotIncreased {
            from: previous.version.clone(),
            to: now.version,
        }),
    }
}

/// Checks the checked-in files against this build. Used by the snapshot test
/// and by `genzo-cli contract check`.
///
/// Line endings are normalized first, so a checkout with CRLF endings passes.
pub fn check_checked_in(ts: &str, lock: &str) -> Result<(), ContractDrift> {
    let lock = ContractLock::from_text(lock).map_err(|_| ContractDrift::Stale)?;
    check_bump(&lock)?;
    if lock != ContractLock::current() || ts.replace("\r\n", "\n") != generate() {
        return Err(ContractDrift::Stale);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lock(version: &str, fingerprint: &str) -> ContractLock {
        ContractLock {
            version: version.into(),
            fingerprint: fingerprint.into(),
        }
    }

    #[test]
    fn unchanged_contract_passes() {
        assert_eq!(check_bump(&ContractLock::current()), Ok(()));
    }

    #[test]
    fn change_without_bump_fails() {
        assert!(matches!(
            check_bump(&lock(CONTRACT_VERSION, "0000000000000000")),
            Err(ContractDrift::VersionNotBumped { .. })
        ));
    }

    #[test]
    fn change_with_lower_version_fails() {
        assert!(matches!(
            check_bump(&lock("99.0.0", "0000000000000000")),
            Err(ContractDrift::VersionNotIncreased { .. })
        ));
    }

    #[test]
    fn change_with_bump_passes() {
        assert_eq!(check_bump(&lock("0.0.1", "0000000000000000")), Ok(()));
    }

    #[test]
    fn crlf_checkout_passes() {
        let ts = generate().replace('\n', "\r\n");
        assert_eq!(
            check_checked_in(&ts, &ContractLock::current().to_text()),
            Ok(())
        );
    }

    #[test]
    fn output_declares_every_type() {
        let ts = generate();
        for name in [
            "Command",
            "Query",
            "Event",
            "TileHeader",
            "AdapterInfo",
            "EngineInfo",
        ] {
            assert!(ts.contains(&format!("export type {name} =")), "{name}");
        }
    }
}
